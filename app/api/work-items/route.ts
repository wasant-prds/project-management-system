import { NextResponse } from 'next/server'
import { workItems } from '@/lib/database/repositories/work-items'
import { projects } from '@/lib/database/repositories/projects'
import { databaseErrorCode } from '@/lib/database/client'
import { getOwner, ownerErrorResponse } from '@/lib/owner'
import { parsePublicId } from '@/lib/public-id'
import { parseWorkItemInput } from '@/lib/work-item-input'
import { shouldStampSubmittedAt } from '@/lib/work-items'
import { currentBangkokWallClockDate } from '@/lib/bangkok-datetime'
import { serializeWorkItem } from '@/lib/work-item-response'
import { parseWorkItemListQuery, queryWorkItemList } from '@/lib/work-item-list'

// GET /api/work-items
export async function GET(request: Request) {
  try {
    const owner = await getOwner()
    const parsed = parseWorkItemListQuery(new URL(request.url).searchParams, owner.id, owner.internalId)
    if (!parsed.success) return parsed.response
    const listed = await queryWorkItemList(parsed.query)
    if ('missing' in listed) {
      return NextResponse.json(
        {
          error: { code: 'NOT_FOUND', message: 'ไม่พบข้อมูลที่อ้างอิง', field: listed.missing },
        },
        { status: 404 },
      )
    }
    return NextResponse.json(listed, { status: 200 })
  } catch (error) {
    const ownerError = ownerErrorResponse(error)
    if (ownerError) return ownerError
    console.error('Error fetching work items:')
    return NextResponse.json(
      { error: { code: 'INTERNAL_ERROR', message: 'Failed to fetch work items' } },
      { status: 500 },
    )
  }
}

// POST /api/work-items
export async function POST(request: Request) {
  try {
    const owner = await getOwner()
    let body: unknown
    try {
      body = await request.json()
    } catch {
      return NextResponse.json(
        { error: { code: 'VALIDATION_ERROR', message: 'Request body must be valid JSON' } },
        { status: 400 },
      )
    }
    const result = parseWorkItemInput(body, owner.id)
    if ('error' in result) {
      return NextResponse.json(
        { error: { code: 'VALIDATION_ERROR', message: result.error } },
        { status: 400 },
      )
    }

    if (result.data.id) {
      return NextResponse.json(
        { error: { code: 'VALIDATION_ERROR', message: 'id is generated by the database', field: 'id' } },
        { status: 400 },
      )
    }
    const projectPublicId = parsePublicId(result.data.projectId)
    if (!projectPublicId) {
      return NextResponse.json(
        { error: { code: 'VALIDATION_ERROR', message: 'ต้องเป็น public UUID', field: 'projectId' } },
        { status: 400 },
      )
    }
    const project = await projects.byPublicId(projectPublicId)

    if (!project) {
      return NextResponse.json(
        { error: { code: 'NOT_FOUND', message: 'Project not found', field: 'projectId' } },
        { status: 404 },
      )
    }

    const now = currentBangkokWallClockDate()
    const workItem = await workItems.create({
      title: result.data.title,
      description: result.data.description,
      kind: result.data.kind,
      priority: result.data.priority,
      role: result.data.role,
      status: result.data.status,
      types: result.data.types,
      workDate: result.data.workDate,
      dueDate: result.data.dueDate,
      projectId: project.id,
      assigneeId: owner.internalId,
      submittedAt: shouldStampSubmittedAt(result.data.status) ? now : null,
    })

    return NextResponse.json({ workItem: serializeWorkItem(workItem) }, { status: 201 })
  } catch (error) {
    const ownerError = ownerErrorResponse(error)
    if (ownerError) return ownerError
    if (databaseErrorCode(error) === '23503') {
      return NextResponse.json(
        { error: { code: 'NOT_FOUND', message: 'Project not found', field: 'projectId' } },
        { status: 404 },
      )
    }
    console.error('Error creating work item:')
    return NextResponse.json(
      { error: { code: 'INTERNAL_ERROR', message: 'Failed to create work item' } },
      { status: 500 },
    )
  }
}
