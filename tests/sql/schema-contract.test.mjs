test('TC-31-15 fingerprint comparison detects an added catalog line and ignores order', () => {
  const left = 'column companies id bigint\ntrigger pms_stamp_company';
  const right = 'trigger pms_stamp_company\ncolumn companies id bigint';
  assert.equal(diffFingerprints(left, right).equal, true);
  const drifted = diffFingerprints(left, `${right}\ncolumn companies drift_marker text`);
  assert.equal(drifted.equal, false);
  assert.deepEqual(drifted.onlyRight, ['column companies drift_marker text']);
});
