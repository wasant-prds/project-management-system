test('schema documents every table and column with PostgreSQL comments and uses snake_case identifiers', () => {
  const tables = [...schema.matchAll(/CREATE TABLE "([^"]+)" \(([\s\S]*?)\n\);/g)];
  const tableComments = [...schema.matchAll(/COMMENT ON TABLE "([^"]+)" IS '((?:[^']|'')+)';/g)];
  const columnComments = [...schema.matchAll(/COMMENT ON COLUMN "([^"]+)"\."([^"]+)" IS '((?:[^']|'')+)';/g)];
  const tableNames = tables.map(([, name]) => name).sort();
  const columnNames = tables.flatMap(([, name, body]) => [...body.matchAll(/^    "([^"]+)" /gm)].map(([, column]) => `${name}.${column}`)).sort();
  assert.deepEqual(tableComments.map(([, name]) => name).sort(), tableNames);
  assert.deepEqual(columnComments.map(([, name, column]) => `${name}.${column}`).sort(), columnNames);
  for (const [, name, body] of tables) {
    assert.match(name, /^[a-z][a-z0-9_]*$/);
    for (const [, column] of body.matchAll(/^    "([^"]+)" /gm)) assert.match(column, /^[a-z][a-z0-9_]*$/);
  }
  for (const [, identifier] of schema.matchAll(/(?:CONSTRAINT|CREATE (?:UNIQUE )?INDEX|CREATE TYPE|CREATE TRIGGER) "([^"]+)"/g)) {
    assert.match(identifier, /^[a-z][a-z0-9_]*$/);
    assert.ok(identifier.length <= 63, `${identifier} exceeds the PostgreSQL identifier limit`);
  }
});

test('external mappings and issue identities use provider-neutral names and provider-scoped unique keys', () => {
  const mappings = tableBody('external_project_mappings');
  const references = tableBody('external_work_item_references');
  for (const body of [mappings, references]) {
    assert.match(body, /"provider" TEXT NOT NULL DEFAULT 'gitlab'/);
    assert.match(body, /"instance_url" TEXT NOT NULL/);
    assert.match(body, /"external_project_id" TEXT NOT NULL/);
    assert.doesNotMatch(body, /"gitlab_[a-z_]+"/);
  }
  assert.match(references, /"external_issue_id" TEXT NOT NULL/);
  assert.match(references, /"external_issue_number" TEXT NOT NULL/);
  assert.match(schema, /"external_project_mappings_source_key" ON "external_project_mappings"\("provider", "instance_url", "external_project_id"\)/);
  assert.match(schema, /"external_work_item_references_source_key" ON "external_work_item_references"\("provider", "instance_url", "external_project_id", "external_issue_id"\)/);
});

