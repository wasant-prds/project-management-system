import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUSINESS_TABLES, MUTABLE_TIMESTAMP_TABLES, TECHNICAL_TABLES, loadArtifacts } from '../../scripts/sql-artifacts.mjs';
import { diffFingerprints } from '../../scripts/sql-catalog.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

const schema = await readFile(new URL('../../database/schema.sql', import.meta.url), 'utf8');
const prismaSchema = await readFile(new URL('../../prisma/schema.prisma', import.meta.url), 'utf8');
const entrypoint = await readFile(new URL('../../scripts/docker-entrypoint-migrate.sh', import.meta.url), 'utf8');
const packageJson = JSON.parse(await readFile(new URL('../../package.json', import.meta.url), 'utf8'));

function tableBody(name) {
  const match = new RegExp(`CREATE TABLE "${name}" \\(([\\s\\S]*?)\\n\\);`).exec(schema);
  assert.ok(match, `Missing table ${name}`);
  return match[1];
}

test('TC-31-01 schema snapshot declares only runtime-used business tables and migration history', () => {
  for (const name of [...BUSINESS_TABLES, ...TECHNICAL_TABLES]) assert.match(schema, new RegExp(`CREATE TABLE "${name}"`));
  assert.equal(schema.match(/CREATE TABLE /g).length, BUSINESS_TABLES.length + TECHNICAL_TABLES.length);
  assert.equal(schema.match(/BIGINT GENERATED BY DEFAULT AS IDENTITY \(START WITH 1 INCREMENT BY 1 NO CYCLE\)/g).length, BUSINESS_TABLES.length + TECHNICAL_TABLES.length);
  assert.doesNotMatch(schema, /CREATE TABLE "(?:Comment|Notification|comments|notifications|legacy_id_mappings)"/);
  assert.doesNotMatch(schema, /timestamptz|TIMESTAMPTZ|cuid\(|IF NOT EXISTS/i);
  assert.doesNotMatch(schema, /postgres(?:ql)?:\/\//i);
  assert.doesNotMatch(schema, /\binsert\s+into\b/i);
  const loaded = loadArtifacts(root);
  assert.equal(loaded.revision, '31.0.0');
  assert.equal(loaded.migrations[0].script, 'database/schema.sql');
});

test('every table has a unique database-generated public UUID and all FKs remain numeric', () => {
  for (const name of [...BUSINESS_TABLES, ...TECHNICAL_TABLES]) {
    const body = tableBody(name);
    assert.match(body, /"public_id" UUID NOT NULL DEFAULT pg_catalog\.gen_random_uuid\(\)/);
    assert.ok(body.includes(`CONSTRAINT "${name}_public_id_key" UNIQUE ("public_id")`));
  }
  for (const [, table, column, target, key] of schema.matchAll(/ALTER TABLE "([^"]+)" ADD CONSTRAINT "[^"]+" FOREIGN KEY \("([^"]+)"\) REFERENCES "([^"]+)"\("([^"]+)"\)/g)) {
    assert.equal(key, 'id');
    assert.ok(tableBody(table).includes(`"${column}" BIGINT`));
    assert.ok(tableBody(target).includes('"id" BIGINT'));
  }
  assert.match(schema, /TG_OP = 'UPDATE' AND NEW\.public_id IS DISTINCT FROM OLD\.public_id/);
});

