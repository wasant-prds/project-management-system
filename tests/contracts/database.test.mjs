import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile, access } from 'node:fs/promises'
import { loadSchema } from '../../scripts/database/schema.mjs'
import { validateSeedSql } from '../../scripts/database/seed.mjs'
import { moduleLoader } from '../support/module-loader.mjs'

test('schema.sql is the sole schema, with no generated ORM or migration copy', async () => {
  const schema = await loadSchema()
  assert.equal(schema.tables.length, 13)
  assert.doesNotMatch(schema.sql, /CREATE TABLE "schema_migrations"|\bINSERT INTO\b|postgres(?:ql)?:\/\//i)
  for (const file of ['prisma/schema.prisma', 'prisma.config.ts', 'database/migrations'])
    await assert.rejects(access(file))
  const pkg = JSON.parse(await readFile('package.json', 'utf8'))
  assert.equal(pkg.dependencies.pg.startsWith('^8.'), true)
  assert.equal(
    Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).some((name) => /prisma/i.test(name)),
    false,
  )
  assert.equal(pkg.scripts.postinstall, undefined)
})
test('all schema tables declare identity IDs, public UUIDs, unique keys and PostgreSQL comments', async () => {
  const { sql, tables } = await loadSchema()
  for (const table of tables) {
    const body = new RegExp(`CREATE TABLE "${table}" \\(([\\s\\S]*?)\\n\\);`).exec(sql)?.[1]
    assert.ok(body)
    assert.match(body, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY/)
    assert.match(body, /"public_id" UUID NOT NULL DEFAULT pg_catalog\.gen_random_uuid\(\)/)
    assert.ok(body.includes(`CONSTRAINT "${table}_public_id_key" UNIQUE ("public_id")`))
    assert.ok(sql.includes(`COMMENT ON TABLE "${table}"`))
    for (const [, column] of body.matchAll(/^    "([a-z_]+)" /gm))
      assert.ok(sql.includes(`COMMENT ON COLUMN "${table}"."${column}"`), `${table}.${column}`)
  }
})
test('nested SQL fragments renumber parameters and never interpolate a user SQL string', () => {
  const { sql, and, literalContains, identifier } = moduleLoader()('lib/database/sql.ts')
  const hostile = "'; DROP TABLE users; --"
  const query = sql`SELECT * FROM work_items WHERE ${and(sql`title=${hostile}`, sql`assignee_id=${7n}`)} AND kind=${'Task'}`
  assert.doesNotMatch(query.text, /DROP TABLE/)
  assert.match(query.text, /title=\$1/)
  assert.match(query.text, /assignee_id=\$2/)
  assert.match(query.text, /kind=\$3/)
  assert.deepEqual([...query.values], [hostile, 7n, 'Task'])
  assert.equal(literalContains('100%_x\\'), '%100\\%\\_x\\\\%')
  assert.throws(() => identifier('users; DROP TABLE users'))
  const forged = { text: 'DROP TABLE users', values: [] }
  const bound = sql`SELECT ${forged}`
  assert.equal(bound.text, 'SELECT $1')
  assert.equal(bound.values[0], forged)
})
test('SQL seed rejects DDL, wrong tables, transaction commands and psql escapes', () => {
  validateSeedSql('INSERT INTO "users"("name") VALUES(\'semi; -- quote\') ON CONFLICT DO NOTHING;', 'users')
  for (const sql of [
    'DROP TABLE users;',
    'INSERT INTO "projects"("name") VALUES(\'a\');',
    'BEGIN; INSERT INTO "users"("name") VALUES(\'a\'); COMMIT;',
    '\\! command',
    'INSERT INTO "users"("name") VALUES((SELECT current_user));',
  ])
    assert.throws(() => validateSeedSql(sql, 'users'))
})
